CREATE TABLE EVENTI (
    ID BIGINT PRIMARY KEY AUTO_INCREMENT(5000),
    NOME VARCHAR(255) NOT NULL,
    NUMEROPOSTI INT NOT NULL,
    DATA DATETIME NOT NULL,
    DURATA BIGINT NOT NULL
);


CREATE TABLE PRENOTAZIONI (
  ID BIGINT PRIMARY KEY AUTO_INCREMENT(5000),
  IDUTENTE BIGINT NOT NULL,
  IDEVENTO BIGINT NOT NULL,
  NUMEROPOSTI INT NOT NULL,
  DATAPRENOTAZIONE DATETIME NOT NULL,
  DATAMODIFICA DATETIME NOT NULL,
  FOREIGN KEY (IDEVENTO) REFERENCES EVENTI(ID) ON DELETE CASCADE
);


CREATE TABLE OPERE (
  ID BIGINT PRIMARY KEY AUTO_INCREMENT(5000),
  NOME VARCHAR(255) NOT NULL,
  AUTORE VARCHAR(255) NOT NULL,
  TIPO BIGINT NOT NULL
);

CREATE TABLE EVENTO_OPERA (
    IDEVENTO BIGINT NOT NULL,
    IDOPERA BIGINT NOT NULL,
    PRIMARY KEY (IDEVENTO, IDOPERA),
    FOREIGN KEY (IDEVENTO) REFERENCES EVENTI(ID) ON DELETE CASCADE,
    FOREIGN KEY (IDOPERA) REFERENCES OPERE(ID)
);

CREATE TABLE FEEDBACK_EVENTI(
    ID BIGINT PRIMARY KEY AUTO_INCREMENT(5000),
    IDUTENTE BIGINT NOT NULL,
    IDEVENTO BIGINT NOT NULL,
    VOTO BIGINT NOT NULL,
    NOTE VARCHAR(255) NOT NULL,
    CONSTRAINT UQ_FEEDBACK_UTENTE_EVENTO UNIQUE (IDUTENTE, IDEVENTO),
    FOREIGN KEY (IDEVENTO) REFERENCES EVENTI(ID) ON DELETE CASCADE);

CREATE TABLE FEEDBACK_OPERE(
    ID BIGINT PRIMARY KEY AUTO_INCREMENT(5000),
    IDUTENTE BIGINT NOT NULL,
    IDOPERA BIGINT NOT NULL,
    VOTO BIGINT NOT NULL,
    NOTE VARCHAR(255) NOT NULL,
    CONSTRAINT UQ_FEEDBACK_UTENTE_OPERA UNIQUE (IDUTENTE, IDOPERA),
    FOREIGN KEY (IDOPERA) REFERENCES OPERE(ID));